/**
 * Report Generation Utilities for SmartAttend
 * Supports PDF, CSV, and Excel exports for all user roles
 */

import { jsPDF } from 'jspdf';

export interface ReportData {
  title: string;
  subtitle?: string;
  generatedAt: Date;
  generatedBy: string;
  period: {
    start: Date;
    end: Date;
    label: string;
  };
  data: any[];
  summary?: Record<string, any>;
}

export interface StudentReportData extends ReportData {
  studentId: string;
  studentName: string;
  courses: {
    courseCode: string;
    courseName: string;
    attendance: number;
    present: number;
    late: number;
    absent: number;
    total: number;
  }[];
  overallAttendance: number;
  grade: string;
}

export interface FacultyReportData extends ReportData {
  facultyId: string;
  facultyName: string;
  sessions: {
    sessionId: string;
    courseCode: string;
    courseName: string;
    date: string;
    time: string;
    totalStudents: number;
    present: number;
    late: number;
    absent: number;
    attendanceRate: number;
  }[];
  totalSessions: number;
  averageAttendance: number;
}

export interface AdminReportData extends ReportData {
  institution: string;
  departments: {
    name: string;
    totalStudents: number;
    totalFaculty: number;
    averageAttendance: number;
    courses: number;
  }[];
  overallStats: {
    totalStudents: number;
    totalFaculty: number;
    totalSessions: number;
    averageAttendance: number;
    attendanceTrend: 'up' | 'down' | 'stable';
  };
}

/**
 * Generate CSV content from report data
 */
export function generateCSV(reportData: ReportData): string {
  const { title, generatedAt, data } = reportData;
  
  // Header
  let csv = `${title}\n`;
  csv += `Generated: ${generatedAt.toLocaleString()}\n`;
  csv += `Period: ${reportData.period.label}\n\n`;
  
  if (data.length === 0) {
    return csv + 'No data available\n';
  }
  
  // Column headers
  const headers = Object.keys(data[0]);
  csv += headers.join(',') + '\n';
  
  // Data rows
  data.forEach(row => {
    const values = headers.map(header => {
      const value = row[header];
      // Escape commas and quotes
      if (typeof value === 'string' && (value.includes(',') || value.includes('"'))) {
        return `"${value.replace(/"/g, '""')}"`;
      }
      return value;
    });
    csv += values.join(',') + '\n';
  });
  
  return csv;
}

/**
 * Generate student attendance report
 */
export function generateStudentReport(data: StudentReportData): string {
  let report = `STUDENT ATTENDANCE REPORT\n`;
  report += `${'='.repeat(60)}\n\n`;
  
  report += `Student: ${data.studentName} (${data.studentId})\n`;
  report += `Period: ${data.period.label}\n`;
  report += `Generated: ${data.generatedAt.toLocaleString()}\n`;
  report += `Generated By: ${data.generatedBy}\n\n`;
  
  report += `OVERALL PERFORMANCE\n`;
  report += `${'-'.repeat(60)}\n`;
  report += `Overall Attendance: ${data.overallAttendance}%\n`;
  report += `Grade: ${data.grade}\n\n`;
  
  report += `COURSE BREAKDOWN\n`;
  report += `${'-'.repeat(60)}\n`;
  
  data.courses.forEach(course => {
    report += `\n${course.courseCode} - ${course.courseName}\n`;
    report += `  Attendance Rate: ${course.attendance}%\n`;
    report += `  Present: ${course.present} | Late: ${course.late} | Absent: ${course.absent}\n`;
    report += `  Total Sessions: ${course.total}\n`;
  });
  
  return report;
}

