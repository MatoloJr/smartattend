/**
 * Download report as file
 */
export function downloadReport(content: string, filename: string, type: 'csv' | 'txt' = 'txt'): void {
  const blob = new Blob([content], { 
    type: type === 'csv' ? 'text/csv;charset=utf-8;' : 'text/plain;charset=utf-8;' 
  });
  
  const link = document.createElement('a');
  const url = URL.createObjectURL(blob);
  
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  link.style.visibility = 'hidden';
  
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  
  URL.revokeObjectURL(url);
}

/**
 * Generate PDF report using jsPDF
 */
export async function generatePDFReport(reportData: ReportData, type: 'student' | 'faculty' | 'admin'): Promise<Blob> {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  let yPosition = margin;
  
  // Helper function to add text with word wrap
  const addText = (text: string, fontSize: number = 10, isBold: boolean = false) => {
    doc.setFontSize(fontSize);
    if (isBold) {
      doc.setFont('helvetica', 'bold');
    } else {
      doc.setFont('helvetica', 'normal');
    }
    
    const lines = doc.splitTextToSize(text, pageWidth - 2 * margin);
    lines.forEach((line: string) => {
      if (yPosition > pageHeight - margin) {
        doc.addPage();
        yPosition = margin;
      }
      doc.text(line, margin, yPosition);
      yPosition += fontSize * 0.5;
    });
    yPosition += 3;
  };
  
  // Add header
  doc.setFillColor(59, 130, 246);
  doc.rect(0, 0, pageWidth, 30, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(reportData.title, pageWidth / 2, 20, { align: 'center' });
  
  yPosition = 40;
  doc.setTextColor(0, 0, 0);
  
  // Add metadata
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  if (reportData.subtitle) {
    doc.text(reportData.subtitle, margin, yPosition);
    yPosition += 6;
  }
  doc.text(`Generated: ${reportData.generatedAt.toLocaleString()}`, margin, yPosition);
  yPosition += 6;
  doc.text(`Period: ${reportData.period.label}`, margin, yPosition);
  yPosition += 10;
  
  // Generate content based on type
  switch (type) {
    case 'student':
      const studentData = reportData as StudentReportData;
      
      // Overall Performance
      addText('OVERALL PERFORMANCE', 14, true);
      addText(`Overall Attendance: ${studentData.overallAttendance}%`);
      addText(`Grade: ${studentData.grade}`);
      yPosition += 5;
      
      // Course Breakdown
      addText('COURSE BREAKDOWN', 14, true);
      studentData.courses.forEach(course => {
        addText(`${course.courseCode} - ${course.courseName}`, 12, true);
        addText(`  Attendance Rate: ${course.attendance}%`);
        addText(`  Present: ${course.present} | Late: ${course.late} | Absent: ${course.absent}`);
        addText(`  Total Sessions: ${course.total}`);
        yPosition += 3;
      });
      break;
      
    case 'faculty':
      const facultyData = reportData as FacultyReportData;
      
      // Summary
      addText('SUMMARY', 14, true);
      addText(`Total Sessions: ${facultyData.totalSessions}`);
      addText(`Average Attendance: ${facultyData.averageAttendance.toFixed(1)}%`);
      yPosition += 5;
      
      // Session Details
      addText('SESSION DETAILS', 14, true);
      facultyData.sessions.slice(0, 20).forEach(session => {
        addText(`${session.date} ${session.time} - ${session.courseCode}`, 11, true);
        addText(`  ${session.courseName}`);
        addText(`  Present: ${session.present} | Late: ${session.late} | Absent: ${session.absent}`);
        addText(`  Attendance Rate: ${session.attendanceRate.toFixed(1)}%`);
        yPosition += 3;
      });
      break;
      
    case 'admin':
      const adminData = reportData as AdminReportData;
      
      // Overall Statistics
      addText('OVERALL STATISTICS', 14, true);
      addText(`Total Students: ${adminData.overallStats.totalStudents}`);
      addText(`Total Faculty: ${adminData.overallStats.totalFaculty}`);
      addText(`Total Sessions: ${adminData.overallStats.totalSessions}`);
      addText(`Average Attendance: ${adminData.overallStats.averageAttendance.toFixed(1)}%`);
      addText(`Trend: ${adminData.overallStats.attendanceTrend.toUpperCase()}`);
      yPosition += 5;
      
      // Department Breakdown
      addText('DEPARTMENT BREAKDOWN', 14, true);
      adminData.departments.forEach(dept => {
        addText(dept.name, 12, true);
        addText(`  Students: ${dept.totalStudents} | Faculty: ${dept.totalFaculty}`);
        addText(`  Courses: ${dept.courses}`);
        addText(`  Average Attendance: ${dept.averageAttendance.toFixed(1)}%`);
        yPosition += 3;
      });
      break;
  }
  
  // Add footer
  // Type assertion to access internal API
  const totalPages = (doc as any).internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(128, 128, 128);
    doc.text(
      `Page ${i} of ${totalPages} | Generated by SmartAttend`,
      pageWidth / 2,
      pageHeight - 10,
      { align: 'center' }
    );
  }
  
  // Return the PDF as a Blob
  return new Promise((resolve) => {
    const blob = doc.output('blob');
    resolve(blob);
  });
}

/**
 * Generate Excel-compatible CSV
 * @returns Blob containing the CSV data
 */
export function generateExcelCSV(reportData: ReportData): Blob {
  const csv = generateCSV(reportData);
  return new Blob([csv], { type: 'text/csv;charset=utf-8;' });
}

/**
 * Download a report file
 */
function downloadCSVReport(reportData: ReportData): void {
  const csv = generateCSV(reportData);
  const filename = `${reportData.title.replace(/\s+/g, '_')}_${Date.now()}.csv`;
  downloadReport(csv, filename, 'csv');
}

/**
 * Format date range for reports
 */
export function formatDateRange(start: Date, end: Date): string {
  const options: Intl.DateTimeFormatOptions = { 
    year: 'numeric', 
    month: 'short', 
    day: 'numeric' 
  };
  
  return `${start.toLocaleDateString('en-US', options)} - ${end.toLocaleDateString('en-US', options)}`;
}

/**
 * Calculate week number in semester
 */
export function getWeekNumber(date: Date, semesterStart: Date): number {
  const diffTime = Math.abs(date.getTime() - semesterStart.getTime());
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
  return Math.ceil(diffDays / 7);
}

/**
 * Generate attendance summary statistics
 */
export function calculateAttendanceStats(records: any[]): {
  total: number;
  present: number;
  late: number;
  absent: number;
  rate: number;
} {
  const total = records.length;
  const present = records.filter(r => r.status === 'present').length;
  const late = records.filter(r => r.status === 'late').length;
  const absent = total - present - late;
  const rate = total > 0 ? (present / total) * 100 : 0;
  
  return { total, present, late, absent, rate };
}

/**
 * Generate weekly attendance breakdown
 */
export function generateWeeklyBreakdown(
  records: any[],
  semesterStart: Date,
  semesterEnd: Date
): Array<{
  week: number;
  label: string;
  start: Date;
  end: Date;
  sessions: number;
  attended: number;
  rate: number;
}> {
  const weeks: any[] = [];
  let currentWeekStart = new Date(semesterStart);
  let weekNumber = 1;
  
  while (currentWeekStart <= semesterEnd) {
    const weekEnd = new Date(currentWeekStart);
    weekEnd.setDate(weekEnd.getDate() + 6);
    
    const weekRecords = records.filter(r => {
      const recordDate = new Date(r.timestamp || r.date);
      return recordDate >= currentWeekStart && recordDate <= weekEnd;
    });
    
    const attended = weekRecords.filter(r => r.status === 'present' || r.status === 'late').length;
    const sessions = weekRecords.length;
    const rate = sessions > 0 ? (attended / sessions) * 100 : 0;
    
    weeks.push({
      week: weekNumber,
      label: `Week ${weekNumber}`,
      start: new Date(currentWeekStart),
      end: weekEnd > semesterEnd ? semesterEnd : weekEnd,
      sessions,
      attended,
      rate
    });
    
    currentWeekStart.setDate(currentWeekStart.getDate() + 7);
    weekNumber++;
  }
  
  return weeks;
}

